import express from "express";
import { requireAuth, requireRole } from "../middleware/auth.js";
import { asyncHandler } from "../utils/asyncHandler.js";
import * as A from "../controllers/analyticsController.js";
import * as U from "../controllers/userController.js";
import * as D from "../controllers/departmentController.js";
import * as S from "../controllers/slaController.js";
import * as E from "../controllers/escalationController.js";
import * as Aud from "../controllers/auditController.js";
const router = express.Router();
router.use(requireAuth, requireRole("admin"));
router.get("/analytics", asyncHandler(A.analytics));
router.get("/users", asyncHandler(U.listUsers));
router.patch("/users/:id/role", asyncHandler(U.updateRole));
router.get("/escalations", asyncHandler(E.listEscalations));
router.get("/audit", asyncHandler(Aud.listAudit));
router.get("/sla", asyncHandler(S.getSLA));
router.patch("/sla/:priority", asyncHandler(S.updateSLA));
router.get("/departments", asyncHandler(D.listDepartments));
router.post("/departments", asyncHandler(D.createDepartment));
router.patch("/departments/:id", asyncHandler(D.updateDepartment));
router.delete("/departments/:id", asyncHandler(D.deleteDepartment));
export default router;
